#!/usr/bin/env node
/* GENERATES assets/mine-masks.json — the Deep Mine's band sprites' collision masks, precomputed (M15 verify).
 * Each entry is `_alphaMask`'s 160-px-long-side mask of one band sprite, reduced to the one test collision
 * makes (alpha >= 128, `markCoverGrid`) and run-length coded: [mw, mh, base64 of LEB128 runs alternating
 * clear/solid, starting clear]. The table is stamped with `window.__ASSET_VER` (the game ignores a table
 * from another version) and with each source file's sha1 (`--check` fails when a band file changed under it).
 *   node scripts/gen-mine-masks.cjs           write the table (boots the game headless, table off)
 *   node scripts/gen-mine-masks.cjs --check   fail (exit 1) unless the table matches the files, the
 *                                              version and a live recomputation, bit for bit
 */
const fs = require('fs'), path = require('path'), crypto = require('crypto');
process.env.NODE_PATH = process.env.NODE_PATH || '/opt/node22/lib/node_modules';
require('module').Module._initPaths();
const H = require(path.join(__dirname, '..', 'tests', 'mine-harness.cjs'));
const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'assets', 'mine-masks.json');
const CHECK = process.argv.includes('--check');

function encode(bits) {
  const out = []; let cur = 0, run = 0;
  const push = (n) => { do { let b = n & 127; n >>>= 7; if (n) b |= 128; out.push(b); } while (n); };
  for (let i = 0; i < bits.length; i++) { const b = bits.charCodeAt(i) - 48; if (b === cur) run++; else { push(run); cur = b; run = 1; } }
  push(run);
  return Buffer.from(out).toString('base64');
}
const sha1 = (f) => crypto.createHash('sha1').update(fs.readFileSync(f)).digest('hex').slice(0, 16);

(async () => {
  const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
  const ver = (/window\.__ASSET_VER = "([^"]+)"/.exec(html) || [])[1];
  if (!ver) { console.error('could not read __ASSET_VER from index.html'); process.exit(2); }
  const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'assets', 'manifest.json'), 'utf8')).assets;
  const fileOf = {}; for (const a of manifest) if (a && a.key && a.file) fileOf[a.key] = a.file;
  const S = await H.start();
  const b = await S.boot('', 390, 844, { returning: true, before: (p) => p.addInitScript(() => { window.MYCELIUM_NO_MASK_TABLE = true; }) });
  await b.page.waitForFunction(() => window.__mineMasks && window.__mineMasks.keys().length > 0, { timeout: 30000 });
  await b.page.evaluate(() => window.__mineMasks.load());
  const keys = await b.page.evaluate(() => window.__mineMasks.keys());
  const masks = {}, files = {};
  for (const k of keys) {
    const m = await b.page.evaluate((key) => window.__mineMasks.live(key), k);
    if (!m) { console.error('no art for ' + k); process.exit(2); }
    masks[k] = [m.mw, m.mh, encode(m.bits)];
    files[k] = sha1(path.join(ROOT, 'assets', fileOf[k]));
  }
  await b.ctx.close(); await S.close();
  const table = { v: 1, ver, n: keys.length, note: 'GENERATED by scripts/gen-mine-masks.cjs — do not hand-edit', masks, files };
  if (CHECK) {
    let old; try { old = JSON.parse(fs.readFileSync(OUT, 'utf8')); } catch (e) { console.error('FAIL: no table at ' + path.relative(ROOT, OUT)); process.exit(1); }
    const bad = [];
    if (old.ver !== ver) bad.push(`ver ${old.ver} != __ASSET_VER ${ver}`);
    for (const k of keys) {
      if (!old.masks || !old.masks[k]) { bad.push(k + ' missing'); continue; }
      if (old.files[k] !== files[k]) bad.push(k + ' file changed');
      if (JSON.stringify(old.masks[k]) !== JSON.stringify(masks[k])) bad.push(k + ' mask differs');
    }
    for (const k of Object.keys(old.masks || {})) if (!masks[k]) bad.push(k + ' no longer a band key');
    if (bad.length) { console.error('FAIL: assets/mine-masks.json is stale — ' + bad.slice(0, 8).join('; ') + (bad.length > 8 ? ` (+${bad.length - 8})` : '') + '\n  regenerate: node scripts/gen-mine-masks.cjs'); process.exit(1); }
    console.log(`ok: ${keys.length} masks match the files, the version (${ver}) and a live recomputation`);
    return;
  }
  fs.writeFileSync(OUT, JSON.stringify(table));
  console.log(`wrote ${path.relative(ROOT, OUT)} — ${keys.length} masks, ${(fs.statSync(OUT).size / 1024).toFixed(1)} KB, ver ${ver}`);
})().catch((e) => { console.error(e); process.exit(2); });
